// The precomputed peeking table behind the Lab's peeking Figure, and its only generator.
//
// The browser looks results up in src/lib/lab/peeking-table.generated.ts instead of simulating, so
// a stale table would misstate what the seeded engine gives. This test owns the table:
// - by default it verifies the committed file and writes nothing: the exact 200 keys in order (a
//   missing, extra or duplicated key fails), the manifest, the canonical serialization, the
//   invariants of every entry, and a fresh run of three cases against the unchanged engine;
// - `PEEK_TABLE_FULL_CHECK=1` regenerates all 200 cases in memory and compares the serialization
//   with the file byte for byte (the build-preparation check);
// - `PEEK_TABLE_WRITE=1` regenerates the file (the only way it is ever written).
// The generator is this Vitest file, not a script, because Vitest resolves the engine's
// extensionless imports. Every case restarts the generator at the same seed.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { gzipSync } from 'node:zlib';
import { describe, expect, it } from 'vitest';
import { simulatePeeking, type PeekInput, type PeekMethod, type PeekResult } from '@/lib/stats/peeking';

const TABLE_PATH = resolve(import.meta.dirname, '../../../src/lib/lab/peeking-table.generated.ts');
const WRITE = process.env.PEEK_TABLE_WRITE === '1';
const FULL_CHECK = process.env.PEEK_TABLE_FULL_CHECK === '1';
/** The whole table takes a while to simulate; only the build-preparation passes run it. */
const FULL_TIMEOUT = 180_000;
/** Three fresh cases, generous for a loaded machine. */
const SPOT_TIMEOUT = 60_000;

/** The simulation every entry shares. Defined here, not read from the file, so a stale manifest fails. */
const MANIFEST = { schemaVersion: 1, seed: 42, runs: 1000, p: 0.35, alpha: 0.05, nPerLook: 100 } as const;
const MAX_LOOKS = 50;
const METHODS: readonly PeekMethod[] = ['naive', 'obf', 'cs'];

type Entry = { readonly falsePositiveRate: number; readonly mcStdError: number; readonly cumulativeByLook: readonly number[] };
type Case = { key: string; input: PeekInput };

/** The 200 cases in table order: daily looks 1 to 50 for each method, then look once after 1 to 50 looks' worth. */
function cases(): Case[] {
  const { seed, runs, p, alpha, nPerLook } = MANIFEST;
  const out: Case[] = [];
  for (const method of METHODS) {
    for (let looks = 1; looks <= MAX_LOOKS; looks += 1) {
      out.push({ key: `daily/${method}/${looks}`, input: { seed, runs, looks, nPerLook, p, alpha, method } });
    }
  }
  // Looking once: the naive test at one look after the same total sample, whatever the fix.
  for (let looks = 1; looks <= MAX_LOOKS; looks += 1) {
    out.push({ key: `once/${looks}`, input: { seed, runs, looks: 1, nPerLook: nPerLook * looks, p, alpha, method: 'naive' } });
  }
  return out;
}

const round3 = (x: number) => Math.round(x * 1000) / 1000;

function entryOf(r: PeekResult): Entry {
  return {
    falsePositiveRate: round3(r.falsePositiveRate),
    mcStdError: round3(r.mcStdError),
    cumulativeByLook: r.cumulativeByLook.map(round3),
  };
}

const HEADER = `// Generated by tests/unit/lab/peeking-table.test.ts with PEEK_TABLE_WRITE=1, from the unchanged
// simulatePeeking engine. Do not edit: that test rejects any table that is not its own output.
//
// Seeded A/A peeking results for the Lab. Both groups convert at the same rate, so every winner
// is a false positive. Each entry holds the share of runs that a method wrongly flagged, its
// Monte Carlo standard error and the share flagged at or before each look, rounded to three
// decimals (exact for the shares, which are whole multiples of one run). Keys:
// \`daily/<method>/<looks>\` checks <looks> times, after every nPerLook visitors per group;
// \`once/<looks>\` is the naive test, checked once after <looks> * nPerLook visitors per group.

export type PeekTableEntry = {
  readonly falsePositiveRate: number;
  readonly mcStdError: number;
  readonly cumulativeByLook: readonly number[];
};
`;

/** The file's exact text: one entry per line, in case order, numbers as JavaScript prints them. */
function serialize(entries: ReadonlyArray<readonly [string, Entry]>): string {
  const m = MANIFEST;
  const lines = entries.map(
    ([key, e]) =>
      `  '${key}': { falsePositiveRate: ${e.falsePositiveRate}, mcStdError: ${e.mcStdError}, cumulativeByLook: [${e.cumulativeByLook.join(', ')}] },`,
  );
  return (
    `${HEADER}\n` +
    `export const PEEK_TABLE_MANIFEST = {\n` +
    `  schemaVersion: ${m.schemaVersion},\n  seed: ${m.seed},\n  runs: ${m.runs},\n  p: ${m.p},\n  alpha: ${m.alpha},\n  nPerLook: ${m.nPerLook},\n` +
    `} as const;\n\n` +
    `export const PEEK_TABLE: Readonly<Record<string, PeekTableEntry>> = {\n${lines.join('\n')}\n};\n`
  );
}

function generate(): { text: string; ms: number } {
  const start = performance.now();
  const entries = cases().map(({ key, input }) => [key, entryOf(simulatePeeking(input))] as const);
  return { text: serialize(entries), ms: performance.now() - start };
}

function sizes(text: string): string {
  return `${Buffer.byteLength(text)} B, ${gzipSync(Buffer.from(text), { level: 9 }).length} B gzip (level 9)`;
}

/** Imported only inside tests, so a missing file fails them instead of the whole file. */
const loadTable = () => import('@/lib/lab/peeking-table.generated');

describe('generation (PEEK_TABLE_WRITE=1 only)', () => {
  it.skipIf(!WRITE)(
    'writes the table from the engine',
    () => {
      const { text, ms } = generate();
      writeFileSync(TABLE_PATH, text);
      console.log(`peeking table written: ${cases().length} entries, ${sizes(text)}, generated in ${Math.round(ms)} ms`);
    },
    FULL_TIMEOUT,
  );
});

describe('the committed peeking table', () => {
  it('exists', () => {
    expect(existsSync(TABLE_PATH), 'missing: run PEEK_TABLE_WRITE=1 npx vitest run tests/unit/lab/peeking-table.test.ts').toBe(true);
  });

  it('lists exactly the 200 keys in order, each once', () => {
    const text = readFileSync(TABLE_PATH, 'utf8');
    // Read from the text: a duplicated key would silently collapse in the imported object.
    const keys = [...text.matchAll(/^ {2}'([^']+)': \{/gm)].map((m) => m[1]);
    const expected = cases().map((c) => c.key);
    expect(expected).toHaveLength(200);
    expect(new Set(expected).size).toBe(200);
    expect(keys).toEqual(expected);
  });

  it('records the shared simulation and the schema version', async () => {
    const { PEEK_TABLE_MANIFEST } = await loadTable();
    expect(PEEK_TABLE_MANIFEST).toEqual(MANIFEST);
  });

  it('is the canonical serialization of its own data (no hand edits, no extra fields)', async () => {
    const { PEEK_TABLE } = await loadTable();
    expect(Object.keys(PEEK_TABLE)).toHaveLength(200);
    for (const e of Object.values(PEEK_TABLE)) {
      expect(Object.keys(e).sort()).toEqual(['cumulativeByLook', 'falsePositiveRate', 'mcStdError']);
    }
    const text = readFileSync(TABLE_PATH, 'utf8');
    expect(serialize(cases().map(({ key }) => [key, PEEK_TABLE[key]!] as const))).toBe(text);
  });

  it('holds valid entries: lengths, monotonic shares in [0, 1], last share = rate, three-decimal values', async () => {
    const { PEEK_TABLE } = await loadTable();
    for (const { key, input } of cases()) {
      const e = PEEK_TABLE[key]!;
      const label = `${key}`;
      // daily: one share per look; once: the single look
      expect(e.cumulativeByLook, label).toHaveLength(input.looks);
      expect(e.cumulativeByLook.at(-1), label).toBe(e.falsePositiveRate);
      for (const [i, v] of e.cumulativeByLook.entries()) {
        expect(Number.isFinite(v) && v >= 0 && v <= 1, `${label} look ${i + 1}`).toBe(true);
        // a share of 1,000 runs is a whole number of runs: three decimals hold it exactly
        expect(Number.isInteger(Math.round(v * MANIFEST.runs)) && round3(v) === v, `${label} look ${i + 1}`).toBe(true);
        if (i > 0) expect(v, `${label} look ${i + 1}`).toBeGreaterThanOrEqual(e.cumulativeByLook[i - 1]!);
      }
      // the rounded standard error is within half a unit of the third decimal of the exact one
      const r = e.falsePositiveRate;
      const exact = Math.sqrt((r * (1 - r)) / MANIFEST.runs);
      expect(Math.abs(e.mcStdError - exact), label).toBeLessThanOrEqual(0.0005 + 1e-12);
      expect(round3(e.mcStdError), label).toBe(e.mcStdError);
    }
  });

  // Always regenerated against the engine, comparing every rounded field.
  const spot = cases().filter((c) => ['daily/naive/20', 'daily/cs/50', 'once/50'].includes(c.key));
  for (const { key, input } of spot) {
    it(
      `${key} matches a fresh run of the engine`,
      async () => {
        const { PEEK_TABLE } = await loadTable();
        expect(PEEK_TABLE[key]).toEqual(entryOf(simulatePeeking(input)));
      },
      SPOT_TIMEOUT,
    );
  }

  it('daily naive at 20 looks flags 22.1% of the runs (the measured preset, not the old 25%)', async () => {
    const { PEEK_TABLE } = await loadTable();
    expect(PEEK_TABLE['daily/naive/20']!.falsePositiveRate).toBe(0.221);
  });

  it.skipIf(!FULL_CHECK)(
    'every entry matches the engine (full regeneration, byte for byte)',
    () => {
      const { text, ms } = generate();
      console.log(`peeking table full check: ${cases().length} entries regenerated in ${Math.round(ms)} ms, ${sizes(text)}`);
      expect(text).toBe(readFileSync(TABLE_PATH, 'utf8'));
    },
    FULL_TIMEOUT,
  );
});
