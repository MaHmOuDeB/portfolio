import { readFileSync } from 'node:fs';
import { formatFact } from '../../../src/lib/facts/format.ts';
import { FACT_ID, collectFacts, renderFactsModule } from '../../../scripts/sources/facts.ts';

type Json = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any
const load = (name: string): Json =>
  JSON.parse(readFileSync(new URL(`../../fixtures/sources/${name}.valid.json`, import.meta.url), 'utf8'));
const inputs = () => [
  { source: 'retention' as const, json: load('retention') },
  { source: 'profile' as const, json: load('profile') },
];

describe('FACT_ID', () => {
  it('accepts <source>.<group>.<name>', () => {
    expect(FACT_ID.test('retention.cohorts.retention_month1')).toBe(true);
    expect(FACT_ID.test('profile.n8n.automated_tests')).toBe(true);
  });

  it('rejects an unknown source, a missing part and a bad character', () => {
    for (const bad of ['audible.a.b', 'retention.cohorts', 'retention.Cohorts.x', 'retention.1a.b', 'retention.a.b.c']) {
      expect(FACT_ID.test(bad), bad).toBe(false);
    }
  });
});

describe('collectFacts', () => {
  it('prefixes each id with its source and sorts by id', () => {
    const facts = collectFacts(inputs());
    const ids = facts.map((f) => f.id);
    expect(ids).toEqual([...ids].sort());
    expect(ids.every((id) => id.startsWith('profile.') || id.startsWith('retention.'))).toBe(true);
    expect(ids).toContain('profile.audible.experiments');
    expect(ids).toContain('retention.cohorts.retention_month1');
    expect(ids.length).toBe(8 + 2);
  });

  it('copies the definition and tags the source', () => {
    const facts = collectFacts(inputs());
    expect(facts.find((f) => f.id === 'retention.cohorts.retention_month1')).toEqual({
      id: 'retention.cohorts.retention_month1',
      value: 0.201,
      unit: 'share',
      decimals: 1,
      label: 'Month-1 retention, size-weighted',
      source: 'retention',
      from: 'results.json#/cohorts/retention_month1',
    });
    expect(facts.find((f) => f.id === 'profile.audible.experiments')).toMatchObject({
      value: 25,
      source: 'profile',
      from: 'profile',
      suffix: '+',
    });
  });

  it('throws on a duplicate id and names it', () => {
    expect(() => collectFacts([...inputs(), { source: 'profile', json: load('profile') }])).toThrow(
      /profile\.audible\.experiments/,
    );
  });

  it('throws on a schema failure and names the source', () => {
    const broken = load('retention');
    delete broken.facts['winback.lapsed_customers'].unit;
    expect(() => collectFacts([{ source: 'retention', json: broken }])).toThrow(/retention/);
  });
});

describe('data/facts/profile.json', () => {
  it('holds the eight approved figures with their display strings', () => {
    const json = JSON.parse(readFileSync(new URL('../../../data/facts/profile.json', import.meta.url), 'utf8'));
    const facts = collectFacts([{ source: 'profile', json }]);
    const shown = Object.fromEntries(facts.map((f) => [f.id, formatFact(f)]));
    expect(shown).toEqual({
      'profile.audible.experiments': '25+',
      'profile.audible.markets': '11',
      'profile.audible.recommendations_adopted': '20+',
      'profile.audible.setup_minutes_after': '3',
      'profile.audible.setup_minutes_before': '20',
      'profile.audible.setup_time_cut': '85%',
      'profile.audible.teams': '3',
      'profile.n8n.automated_tests': '270+',
    });
  });
});

describe('renderFactsModule', () => {
  const facts = collectFacts(inputs());
  const out = renderFactsModule(facts);

  it('has the generated header and a type-only import', () => {
    expect(out.startsWith('// Generated by scripts/sync-sources.ts. Do not edit.\n')).toBe(true);
    expect(out).toContain("import type { FactDef } from './types.ts';");
  });

  it('exports FACTS, FactId and FACT_DISPLAYS', () => {
    expect(out).toContain('as const satisfies Record<string, FactDef>');
    expect(out).toContain('export type FactId = keyof typeof FACTS;');
    expect(out).toContain('export const FACT_DISPLAYS: readonly string[]');
    expect(out).toContain('"profile.audible.experiments"');
  });

  it('is byte-identical for the same input and ends with a newline', () => {
    expect(renderFactsModule(collectFacts(inputs()))).toBe(out);
    expect(out.endsWith('\n')).toBe(true);
  });

  it('lists the sorted unique display strings', () => {
    const m = /FACT_DISPLAYS: readonly string\[\] = (\[[\s\S]*?\]);/.exec(out);
    const listed = JSON.parse(m![1]!) as string[];
    expect(listed).toEqual([...listed].sort());
    expect(new Set(listed).size).toBe(listed.length);
    for (const d of ['25+', '270+', '85%', '20.1%', '3,351']) expect(listed, d).toContain(d);
  });
});
