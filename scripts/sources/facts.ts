// Collects the facts of every site export into one sorted list and renders the generated
// facts module (src/lib/facts/facts.generated.ts, written by scripts/sync-sources.ts).
import { formatFact } from '../../src/lib/facts/format.ts';
import type { FactDef, SourceId } from '../../src/lib/facts/types.ts';
import { validateExport } from './schema.ts';

export const FACT_ID = /^(retention|retail|weather|pulse|profile)\.[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$/;

type Input = { source: SourceId | 'profile'; json: unknown };
type RawFact = Omit<FactDef, 'id' | 'source'>;

const byId = (a: { id: string }, b: { id: string }) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);

export function collectFacts(inputs: Input[]): FactDef[] {
  const seen = new Map<string, FactDef>();
  for (const { source, json } of inputs) {
    const result = validateExport(json, `${source}/1`);
    if (!result.ok) throw new Error(`${source} export fails ${source}/1: ${result.errors.join('; ')}`);
    const facts = (json as { facts: Record<string, RawFact> }).facts;
    for (const [key, raw] of Object.entries(facts)) {
      const id = `${source}.${key}`;
      if (!FACT_ID.test(id)) throw new Error(`bad fact id '${id}' in ${source} export`);
      if (seen.has(id)) throw new Error(`duplicate fact id '${id}' in ${source} export`);
      const def: FactDef = {
        id,
        value: raw.value,
        unit: raw.unit,
        decimals: raw.decimals,
        label: raw.label,
        source,
        from: raw.from,
      };
      if (raw.suffix !== undefined) def.suffix = raw.suffix;
      if (raw.scale !== undefined) def.scale = raw.scale;
      seen.set(id, def);
    }
  }
  return [...seen.values()].sort(byId);
}

export function renderFactsModule(facts: FactDef[]): string {
  const entries = facts.map((f) => `  ${JSON.stringify(f.id)}: ${JSON.stringify(f)},`);
  // FACT_DISPLAYS is baked from Node's ICU en-GB Intl output, so an ICU update in Node can make
  // `--check` report the generated file stale. Regenerate it with `npm run sources:sync`.
  const displays = [...new Set(facts.map((f) => formatFact(f)))].sort();
  return [
    '// Generated by scripts/sync-sources.ts. Do not edit.',
    "import type { FactDef } from './types.ts';",
    '',
    'export const FACTS = {',
    ...entries,
    '} as const satisfies Record<string, FactDef>;',
    '',
    'export type FactId = keyof typeof FACTS;',
    '',
    `export const FACT_DISPLAYS: readonly string[] = ${JSON.stringify(displays, null, 2)};`,
    '',
  ].join('\n');
}
