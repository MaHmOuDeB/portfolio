import { readFileSync, writeFileSync } from 'node:fs';

const REFERENCE = 'stats-ref/reference.json';
const OUTPUT = 'src/lib/stats/obf-constants.generated.ts';
const LOOKS = 60;
const PER_ROW = 4;

/**
 * The text of `obf-constants.generated.ts`, built from the `obf` table of `reference.json`
 * (keys "1" to "60"). Throws when a look is missing or not a finite number.
 */
export function generateObfConstants(referenceJson: string): string {
  const obf = (JSON.parse(referenceJson) as { obf?: Record<string, unknown> }).obf;
  const values: number[] = [];
  for (let k = 1; k <= LOOKS; k += 1) {
    const v = obf?.[String(k)];
    if (typeof v !== 'number' || !Number.isFinite(v)) {
      throw new Error(`reference.json obf["${k}"] must be a finite number, got ${String(v)}`);
    }
    values.push(v);
  }
  const rows: string[] = [];
  for (let i = 0; i < values.length; i += PER_ROW) {
    rows.push(`  ${values.slice(i, i + PER_ROW).join(', ')},`);
  }
  return [
    `// Generated by scripts/gen-obf-constants.ts from the "obf" table of ${REFERENCE}. Do not edit.`,
    '',
    '/**',
    ' * O\'Brien-Fleming boundary constants: index K - 1 holds the two-sided 0.95 critical value for K',
    ' * equally spaced looks (K = 1 to 60). K = 1 is exact; the rest are Monte Carlo estimates.',
    ' */',
    'export const OBF_CONSTANTS: readonly number[] = [',
    ...rows,
    '];',
    '',
  ].join('\n');
}

function main(): void {
  const text = generateObfConstants(readFileSync(REFERENCE, 'utf8'));
  if (process.argv.includes('--check')) {
    let committed = '';
    try {
      committed = readFileSync(OUTPUT, 'utf8');
    } catch {
      // A missing file counts as stale.
    }
    if (committed !== text) {
      console.error(`${OUTPUT} is stale: run "node scripts/gen-obf-constants.ts" and commit it.`);
      process.exit(1);
    }
    return;
  }
  writeFileSync(OUTPUT, text);
}

if (process.argv[1]?.endsWith('gen-obf-constants.ts')) main();
