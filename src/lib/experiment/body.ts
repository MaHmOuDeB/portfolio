// Reads a request body with a hard byte cap. `request.text()` would buffer a body of any size, and
// Content-Length can be absent (chunked) or wrong, so the stream is read chunk by chunk and dropped
// as soon as it passes the limit.

/** Reads at most `limit` bytes; null when the body is longer (Content-Length absent or wrong). */
export async function readCapped(request: Request, limit: number): Promise<string | null> {
  if (request.body === null) return '';
  const reader = request.body.getReader();
  const chunks: Uint8Array[] = [];
  let size = 0;
  try {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      size += value.byteLength;
      if (size > limit) {
        await reader.cancel().catch(() => {});
        return null;
      }
      chunks.push(value);
    }
  } finally {
    reader.releaseLock();
  }
  const bytes = new Uint8Array(size);
  let offset = 0;
  for (const c of chunks) {
    bytes.set(c, offset);
    offset += c.byteLength;
  }
  return new TextDecoder().decode(bytes);
}
